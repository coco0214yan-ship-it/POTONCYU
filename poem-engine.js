  function normalizeTopic(topic) {
    return String(topic || "").normalize("NFKC").trim().replace(/\s+/g, " ");
  }

  function classify(topic) {
    const normalized = normalizeTopic(topic);
    return topicRules.find(([, pattern]) => pattern.test(normalized))?.[0] || "open";
  }

  function shuffled(items) {
    const result = [...items];
    for (let i = result.length - 1; i > 0; i -= 1) {
      const j = Math.floor(Math.random() * (i + 1));
      [result[i], result[j]] = [result[j], result[i]];
    }
    return result;
  }

  function validDraft(draft, topic) {
    return Boolean(draft && Array.isArray(draft.lines) && draft.lines.length === 5
      && draft.lines[2] === BLANK && draft.lines.filter((line) => line === BLANK).length === 1
      && draft.lines.every((line) => typeof line === "string" && line.length > 0 && Array.from(line).length <= 24 && !/[\r\n<>]/.test(line))
      && (!topic || draft.lines.some((line) => normalizeTopic(line).includes(normalizeTopic(topic))))
      && Array.isArray(draft.choices) && draft.choices.length === 4 && new Set(draft.choices).size === 4
      && draft.choices.every((choice) => typeof choice === "string" && choice.trim() && Array.from(choice).length <= 12 && !/[\r\n<>]/.test(choice) && !choice.includes(BLANK)));
  }

  function isAction(choice) {
    return /たい|てる|いる|ない|なかった|迷う|迷って|待つ|待って|言う|言え|する|なる|ほしい|しまう|続く|行く|歩く|聞く|寝る|思う|あげる|食べる|頑張る|残る|忘れる|開く|もらう|選ぶ|撮る|出す|見る|言って|みる|忘れ|聞いて|残して|伝え|して|食べ|泣ける|見送る/.test(choice);
  }

  function createProvider(legacyTemplates = []) {
    const topics = new Map();
    function stateFor(topic) {
      if (!topics.has(topic)) {
        if (topics.size >= 60) topics.delete(topics.keys().next().value);
        topics.set(topic, { remaining: [], recent: [], last: "" });
      }
      return topics.get(topic);
    }
    function candidates(topic) {
      const category = classify(topic);
      const rows = category === "open" ? scenes.open : [...scenes[category], ...scenes.open.slice(0, 12)];
      const result = rows.map(([second, fourth, fifth, choices], index) => ({
        templateId: `${category}-${index}`, topic, source: "local",
        lines: [topic, second, BLANK, fourth, fifth], choices,
      }));
      for (const template of legacyTemplates) {
        if (!template.tags.includes(topic) || template.choices.filter(isAction).length < 2) continue;
        const draft = { templateId: template.id, topic, source: "local", lines: template.lines, choices: template.choices };
        if (validDraft(draft, topic)) result.push(draft);
      }
      return [...new Map(result.map((draft) => [draft.lines.join("\n"), draft])).values()];
    }
    function remember(topic, draft) {
      const state = stateFor(topic);
      const signature = draft.lines.join("\n");
      state.last = signature;
      state.remaining = state.remaining.filter((item) => item.lines.join("\n") !== signature);
      state.recent = [draft.lines, ...state.recent.filter((lines) => lines.join("\n") !== signature)].slice(0, 32);
    }
    return {
      generate(rawTopic, previousTemplateId = "") {
        const topic = normalizeTopic(rawTopic);
        if (!topic || Array.from(topic).length > 10) throw new Error("お題は1〜10字で入れてください。");
        const state = stateFor(topic);
        if (!state.remaining.length) {
          state.remaining = shuffled(candidates(topic));
          const next = state.remaining.findIndex((item) => item.lines.join("\n") !== state.last && item.templateId !== previousTemplateId);
          if (next > 0) [state.remaining[0], state.remaining[next]] = [state.remaining[next], state.remaining[0]];
        }
        const draft = state.remaining.shift();
        remember(topic, draft);
        return { ...draft, lines: [...draft.lines], choices: shuffled(draft.choices) };
      },
      accept(rawTopic, draft) {
        const topic = normalizeTopic(rawTopic);
        if (!validDraft(draft, topic)) return null;
        const state = stateFor(topic);
        if (state.recent.some((lines) => lines.join("\n") === draft.lines.join("\n"))) return null;
        const result = { ...draft, topic, source: "ai", choices: shuffled(draft.choices) };
        remember(topic, result);
        return result;
      },
      recent(rawTopic) { return stateFor(normalizeTopic(rawTopic)).recent.slice(0, 5); },
      count(rawTopic) { return candidates(normalizeTopic(rawTopic)).length; },
    };
  }


const fs = require("node:fs");
const path = require("node:path");
const tanka = require("../functions/lib/tanka-contract");
const { readingsFor } = require("../functions/lib/japanese-reading");

async function main() {
  const source = require("../functions/lib/feeling-catalog.json");
  const catalog = [];
  for (const group of source) {
    const poems = [];
    for (const [index, draft] of group.poems.entries()) {
      const readings = await readingsFor(draft.lines.filter((line) => line !== tanka.BLANK));
      readings.splice(2, 0, "");
      const choiceReadings = await readingsFor(draft.choices);
      const annotated = { ...draft, readings, choiceReadings, templateId: `sample_${group.id}_${index}`, source: "sample" };
      if (!tanka.validDraft(annotated)) {
        throw new Error(`${annotated.templateId}: lines=${readings.map(tanka.countMora)}, choices=${choiceReadings.map(tanka.countMora)}`);
      }
      poems.push(annotated);
    }
    catalog.push({ ...group, poems });
  }
  const output = "// Generated by scripts/build-feeling-catalog.cjs; do not edit.\n(function(root) {\n  const catalog = "
    + JSON.stringify(catalog, null, 2) + ";\n  if (typeof module !== 'undefined' && module.exports) module.exports = catalog;\n  else root.PotonchuFeelingCatalog = catalog;\n})(globalThis);\n";
  fs.writeFileSync(path.resolve(__dirname, "../functions/lib/feeling-catalog-data.js"), output);
  console.log(`Validated ${catalog.reduce((sum, group) => sum + group.poems.length, 0)} drafts, all four choices in 5-7-5-7-7.`);
}
main().catch((error) => { console.error(error.message); process.exitCode = 1; });
